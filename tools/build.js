'use strict';
/**
 * Builds the single-file ChillAll package.
 *
 *   node tools/build.js          # generate chillall/src/chillall.js, bundle, emit .d.ts
 *   node tools/build.js --check  # build to memory only, fail if anything is off (CI)
 *
 * Output (chillall/dist):
 *   chillall.esm.js / .esm.min.js   ESM, named exports `ChillButton`… + default `ChillAll` (tree-shakeable, no globals)
 *   chillall.cjs                    CommonJS (require('chillall'))
 *   chillall.js / chillall.min.js   IIFE for <script>: window.ChillAll + every window.ChillXxx global
 *   chillall.d.ts                   generated typings
 */
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');
const { ROOT, libs, load, sourceFile, globalName } = require('./env');
const manifest = require('./manifest');
const { minifyCssInJs } = require('./cssmin');

const OUT = path.join(ROOT, 'chillall');
const DIST = path.join(OUT, 'dist');
const check = process.argv.includes('--check');

// ---------------------------------------------------------------- discover
const onDisk = libs();
const ordered = [];
const category = {};
for (const [cat, names] of Object.entries(manifest.categories)) {
    for (const n of names) if (onDisk.includes(n)) { ordered.push(n); category[n] = cat; }
}
for (const n of onDisk) {
    if (!ordered.includes(n)) { console.warn(`! ${n} is not in tools/manifest.js -> category "misc"`); ordered.push(n); category[n] = 'misc'; }
}
const meta = ordered.map(name => {
    const src = fs.readFileSync(sourceFile(name), 'utf8');
    const g = globalName(src);
    if (!g) throw new Error(`${name}: cannot find window.ChillXxx assignment`);
    return { name, global: g, key: g.slice('Chill'.length), category: category[name], src };
});
const dupKeys = meta.map(m => m.key).filter((k, i, a) => a.indexOf(k) !== i);
if (dupKeys.length) throw new Error('duplicate component keys: ' + dupKeys.join(', '));

// ---------------------------------------------------------------- generate ESM entry
const cats = {};
for (const m of meta) (cats[m.category] = cats[m.category] || []).push(m.name.slice('chill'.length));

let gen = `/**
 * ChillAll v${manifest.version} - every ChillLib component in ONE package.
 * ${meta.length} zero-dependency components. GENERATED by tools/build.js from the per-component src folders - do not edit.
 * @license MIT
 */
`;
for (const m of meta) {
    // Each component keeps its original IIFE; we hand it a private CommonJS-style \`module\`.
    gen += `\n// ---- ${m.global} (${m.category}) ----\nconst ${m.global} = /* @__PURE__ */ (function () {\nconst module = { exports: {} }; const exports = module.exports;\n${m.src}\n;return module.exports;\n})();\n`;
}
gen += `
export const VERSION = ${JSON.stringify(manifest.version)};
export const categories = ${JSON.stringify(cats, null, 2)};
export const components = ${JSON.stringify(meta.map(m => ({ name: m.name.slice(5), global: m.global, key: m.key, category: m.category })))};

export { ${meta.map(m => m.global).join(', ')} };

// Built inside a PURE-annotated function so bundlers can drop the whole registry (and with it every
// component) when a consumer only imports named components such as { ChillButton }.
function buildChillAll() {
const registry = { ${meta.map(m => `${m.key}: ${m.global}`).join(', ')} };
const api = Object.assign({ version: VERSION, totalLibraries: ${meta.length} }, registry, {
    categories,
    components,
    /** Look up a component by key ('Button'), lowercase name ('button') or global name ('ChillButton'). */
    get(name) {
        const k = String(name).replace(/^chill/i, '').toLowerCase();
        const hit = components.find(c => c.key.toLowerCase() === k);
        return hit ? registry[hit.key] : undefined;
    },
    /** Pre-inject the CSS of the given components (all if omitted) so first paint has no style flash. */
    injectCSS(names) {
        const list = names ? [].concat(names) : components.map(c => c.key);
        list.forEach(n => { const lib = api.get(n); if (lib && typeof lib.injectCSS === 'function') { try { lib.injectCSS(); } catch (e) { /* needs DOM */ } } });
    }
});
return api;
}

export const ChillAll = /* @__PURE__ */ buildChillAll();

export default ChillAll;
`;

// IIFE wrapper entry (browser globals, back-compat with the per-component <script> tags)
const globalEntry = `import ChillAll, { ${meta.map(m => m.global).join(', ')} } from './chillall.js';
if (typeof window !== 'undefined') {
    window.ChillAll = ChillAll;
    ${meta.map(m => `if (!window.${m.global}) window.${m.global} = ${m.global};`).join('\n    ')}
}
export default ChillAll;
`;

// ---------------------------------------------------------------- typings (introspected)
function dts() {
    let out = `/**\n * ChillAll v${manifest.version} - TypeScript definitions (generated by tools/build.js).\n * Component APIs are introspected from the sources; option bags are typed loosely.\n */\n\n`;
    out += `export type ChillOptions = Record<string, any>;\n\n`;
    const names = [];
    for (const m of meta) {
        let lib; try { lib = load(m.name).lib; } catch (e) { lib = {}; }
        const members = [];
        for (const k of Object.keys(lib || {})) {
            if (!/^[A-Za-z_$][\w$]*$/.test(k)) continue;
            const v = lib[k];
            if (k === 'version') members.push('version: string;');
            else if (typeof v === 'function' && /^class\s/.test(Function.prototype.toString.call(v))) members.push(`${k}: new (...args: any[]) => any;`);
            else if (typeof v === 'function') members.push(`${k}(...args: any[]): any;`);
            else if (Array.isArray(v)) members.push(`${k}: any[];`);
            else members.push(`${k}: ${typeof v === 'string' ? 'string' : typeof v === 'number' ? 'number' : typeof v === 'boolean' ? 'boolean' : 'any'};`);
        }
        if (typeof lib === 'function') members.push('(...args: any[]): any;');
        members.push('[key: string]: any;');
        out += `export interface ${m.global}Static {\n${members.map(x => '    ' + x).join('\n')}\n}\n`;
        out += `export const ${m.global}: ${m.global}Static;\n\n`;
        names.push(m);
    }
    out += `export interface ComponentInfo { name: string; global: string; key: string; category: string; }\n\n`;
    out += `export interface ChillAllStatic {\n    version: string;\n    totalLibraries: number;\n${names.map(m => `    ${m.key}: ${m.global}Static;`).join('\n')}\n`;
    out += `    categories: Record<string, string[]>;\n    components: ComponentInfo[];\n    get(name: string): any;\n    injectCSS(names?: string | string[]): void;\n}\n\n`;
    out += `export const VERSION: string;\nexport const categories: Record<string, string[]>;\nexport const components: ComponentInfo[];\nexport const ChillAll: ChillAllStatic;\nexport default ChillAll;\n\n`;
    out += `declare global {\n    interface Window {\n        ChillAll: ChillAllStatic;\n${names.map(m => `        ${m.global}: ${m.global}Static;`).join('\n')}\n    }\n}\n`;
    return out;
}

// ---------------------------------------------------------------- run
(async () => {
    const entryEsm = path.join(OUT, 'src', 'chillall.js');
    const entryGlobal = path.join(OUT, 'src', 'chillall.global.js');
    const banner = `/*! ChillAll v${manifest.version} | MIT | ${meta.length} components */`;
    const common = { bundle: true, banner: { js: banner }, legalComments: 'none', logLevel: 'warning', target: 'es2018' };

    if (!check) {
        fs.mkdirSync(path.join(OUT, 'src'), { recursive: true });
        fs.mkdirSync(DIST, { recursive: true });
        fs.writeFileSync(entryEsm, gen);
        fs.writeFileSync(entryGlobal, globalEntry);
    }
    const builds = [
        ['chillall.esm.js', { format: 'esm' }],
        ['chillall.esm.min.js', { format: 'esm', minify: true }],
        ['chillall.cjs', { format: 'cjs' }],
        ['chillall.js', { format: 'iife', globalName: 'ChillAllBundle', entry: entryGlobal, footer: { js: 'if (typeof window !== "undefined") window.ChillAll = ChillAllBundle.default;' } }],
        ['chillall.min.js', { format: 'iife', minify: true, globalName: 'ChillAllBundle', entry: entryGlobal, footer: { js: 'if (typeof window !== "undefined") window.ChillAll = ChillAllBundle.default;' } }]
    ];
    if (check) { // esbuild needs files on disk; use a temp dir
        const tmp = fs.mkdtempSync(path.join(require('os').tmpdir(), 'chillall-'));
        fs.writeFileSync(path.join(tmp, 'chillall.js'), gen);
        fs.writeFileSync(path.join(tmp, 'chillall.global.js'), globalEntry);
        await esbuild.build({ ...common, entryPoints: [path.join(tmp, 'chillall.global.js')], outfile: path.join(tmp, 'o.js'), format: 'iife' });
        console.log(`check ok: ${meta.length} components bundle cleanly`);
        return;
    }
    for (const [file, o] of builds) {
        const { entry, ...opts } = o;
        // Minified builds also collapse the CSS that lives inside template literals (esbuild leaves those untouched).
        const plugins = opts.minify ? [{
            name: 'chillall-cssmin',
            setup(b) {
                b.onLoad({ filter: /chillall\.js$/ }, a => ({ contents: minifyCssInJs(fs.readFileSync(a.path, 'utf8')), loader: 'js' }));
            }
        }] : [];
        await esbuild.build({ ...common, ...opts, plugins, entryPoints: [entry || entryEsm], outfile: path.join(DIST, file) });
    }
    fs.writeFileSync(path.join(DIST, 'chillall.d.ts'), dts());
    // keep a copy of the stand-alone sources in sync too
    for (const m of meta) if (m.name !== 'chillalert') fs.copyFileSync(sourceFile(m.name), path.join(ROOT, m.name, 'dist', m.name + '.js'));

    const kb = f => (fs.statSync(path.join(DIST, f)).size / 1024).toFixed(1) + ' KB';
    console.log(`ChillAll v${manifest.version}: ${meta.length} components`);
    for (const c of Object.keys(cats)) console.log(`  ${c.padEnd(13)} ${cats[c].length}`);
    for (const [f] of builds) console.log(`  dist/${f.padEnd(20)} ${kb(f)}`);
    console.log(`  dist/chillall.d.ts`.padEnd(27) + kb('chillall.d.ts'));
})().catch(e => { console.error(e); process.exit(1); });

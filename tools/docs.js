'use strict';
/**
 * Generates chillall/COMPONENTS.md (catalog of every component, introspected from the real code).
 *   node tools/docs.js
 */
const fs = require('fs');
const path = require('path');
const { load, ROOT, libs, sourceFile, globalName } = require('./env');
const manifest = require('./manifest');

const cats = {};
for (const [cat, names] of Object.entries(manifest.categories)) for (const n of names) if (libs().includes(n)) (cats[cat] = cats[cat] || []).push(n);

const pretty = { core: 'Core', formControls: 'Form controls', navigation: 'Navigation', feedback: 'Feedback & overlays', display: 'Display', data: 'Data', utility: 'Utilities' };
const firstLine = src => {
    const m = src.match(/\/\*\*?\s*\n?\s*\*?\s*(Chill[A-Za-z]+)\s*[-–—:]\s*([^\n*]+)/);
    return m ? m[2].trim().replace(/\s+$/, '') : '';
};

let out = `# ChillAll component catalog

${libs().length} components · generated by \`node tools/docs.js\` from the real sources (version, public API). Every component is
zero-dependency, SSR-safe to import, dark-mode aware (\`<html data-theme="dark">\` / \`.dark\` or OS preference), keyboard accessible and has \`destroy()\`.

`;
for (const [cat, names] of Object.entries(cats)) {
    out += `## ${pretty[cat] || cat} (${names.length})\n\n| Component | Global / export | Version | Public API |\n|---|---|---|---|\n`;
    for (const n of names) {
        const src = fs.readFileSync(sourceFile(n), 'utf8');
        const g = globalName(src);
        let lib = {};
        try { lib = load(n).lib; } catch (e) { /* listed without API */ }
        const api = Object.keys(lib).filter(k => typeof lib[k] === 'function' && /^[a-z]/.test(k)).map(k => '`' + k + '`').join(' ');
        const desc = firstLine(src);
        out += `| **${n.slice(5)}**${desc ? '<br><sub>' + desc.replace(/\|/g, '/') + '</sub>' : ''} | \`${g}\` | ${lib.version || ''} | ${api} |\n`;
    }
    out += '\n';
}
fs.writeFileSync(path.join(ROOT, 'chillall', 'COMPONENTS.md'), out);
console.log('wrote chillall/COMPONENTS.md (' + libs().length + ' components)');

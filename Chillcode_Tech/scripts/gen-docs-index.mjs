// Regenerates the docs indexes. Run after adding/removing doc or guide files:
//   node scripts/gen-docs-index.mjs
//   - src/docs/content/index.ts      lazy-loaded array with every DocEntry
//   - src/docs/guides/index.ts       lazy-loaded array with every Guide
//   - src/docs/nav.generated.ts      LIGHT metadata (titles/summaries/keywords) for sidebar + search + landing
import { createRequire } from 'node:module';
import { readdirSync, writeFileSync, statSync, existsSync, mkdtempSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, '..');
const contentRoot = join(site, 'src', 'docs', 'content');
const guidesRoot = join(site, 'src', 'docs', 'guides');
const require = createRequire(join(site, '..', 'tools', 'package.json'));
const esbuild = require('esbuild');

const files = [];
for (const cat of readdirSync(contentRoot).sort()) {
    const dir = join(contentRoot, cat);
    if (!statSync(dir).isDirectory()) continue;
    for (const f of readdirSync(dir).sort()) if (f.endsWith('.ts')) files.push({ cat, id: f.replace(/\.ts$/, ''), path: join(dir, f) });
}
mkdirSync(guidesRoot, { recursive: true });
const guideFiles = existsSync(guidesRoot) ? readdirSync(guidesRoot).sort().filter(f => f.endsWith('.ts') && f !== 'index.ts' && f !== 'loaders.ts').map(f => ({ id: f.replace(/\.ts$/, ''), path: join(guidesRoot, f) })) : [];

const ident = (p, pre) => pre + p.replace(/[^a-z0-9]/gi, '_');
let idx = `// GENERATED by scripts/gen-docs-index.mjs - do not edit.\nimport type { DocEntry } from '../types';\n\n`;
for (const f of files) idx += `import ${ident(f.cat + '_' + f.id, 'd_')} from './${f.cat}/${f.id}';\n`;
idx += `\nexport const entries: DocEntry[] = [\n${files.map(f => `    ${ident(f.cat + '_' + f.id, 'd_')},`).join('\n')}\n];\n`;
writeFileSync(join(contentRoot, 'index.ts'), idx);

let gidx = `// GENERATED by scripts/gen-docs-index.mjs - do not edit.\nimport type { Guide } from '../types';\n\n`;
for (const g of guideFiles) gidx += `import ${ident(g.id, 'g_')} from './${g.id}';\n`;
gidx += `\nexport const guides: Guide[] = [\n${guideFiles.map(g => `    ${ident(g.id, 'g_')},`).join('\n')}\n];\n`;
writeFileSync(join(guidesRoot, 'index.ts'), gidx);

// per-entry lazy loaders: a page only downloads its own doc
const NL = String.fromCharCode(10);
const loaderFile = (type, entries) => [
    '// GENERATED by scripts/gen-docs-index.mjs - do not edit.',
    `import type { ${type} } from '../types';`,
    '',
    `export const loaders: Record<string, () => Promise<{ default: ${type} }>> = {`,
    ...entries.map(([id, path]) => `    '${id}': () => import('${path}'),`),
    '};',
    '',
].join(NL);
writeFileSync(join(contentRoot, 'loaders.ts'), loaderFile('DocEntry', files.map(f => [f.id, `./${f.cat}/${f.id}`])));
writeFileSync(join(guidesRoot, 'loaders.ts'), loaderFile('Guide', guideFiles.map(x => [x.id, `./${x.id}`])));

// light nav metadata: compile the real content once, keep only small fields
const tmp = mkdtempSync(join(tmpdir(), 'chillnav-'));
const stdin = files.map((f, i) => `import d${i} from ${JSON.stringify(f.path.replace(/\\/g, '/'))};`).join('\n') +
    guideFiles.map((g, i) => `\nimport g${i} from ${JSON.stringify(g.path.replace(/\\/g, '/'))};`).join('') +
    `\nexport const entries = [${files.map((_, i) => 'd' + i).join(',')}];\nexport const guides = [${guideFiles.map((_, i) => 'g' + i).join(',')}];`;
await esbuild.build({ stdin: { contents: stdin, resolveDir: contentRoot, loader: 'ts' }, bundle: true, format: 'esm', platform: 'node', outfile: join(tmp, 'n.mjs'), logLevel: 'error' });
const { entries, guides } = await import(pathToFileURL(join(tmp, 'n.mjs')).href);

// reading order for the guides (anything new goes last, alphabetically)
const GUIDE_ORDER = ['introduction', 'installation', 'vanilla', 'react', 'nextjs', 'vue', 'theming', 'accessibility', 'security', 'migration',
    'recipe-login-form', 'recipe-data-table', 'recipe-command-palette', 'recipe-dashboard', 'recipe-file-upload'];
const rank = id => { const i = GUIDE_ORDER.indexOf(id); return i === -1 ? 999 : i; };
guides.sort((a, b) => rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));

const nav = entries.map(e => ({ id: e.id, global: e.global, title: e.title, category: e.category, summary: e.summary, keywords: e.keywords || [] }));
const gnav = guides.map(g => ({ id: g.id, title: g.title, summary: g.summary, group: g.group }));
const out = `// GENERATED by scripts/gen-docs-index.mjs - do not edit.\nimport type { CategoryId, Guide } from './types';\n\n` +
    `export interface NavItem { id: string; global: string; title: string; category: CategoryId; summary: string; keywords: string[] }\n` +
    `export interface GuideNavItem { id: string; title: string; summary: string; group: Guide['group'] }\n\n` +
    `export const componentNav: NavItem[] = ${JSON.stringify(nav, null, 2)};\n\n` +
    `export const guideNav: GuideNavItem[] = ${JSON.stringify(gnav, null, 2)};\n`;
writeFileSync(join(site, 'src', 'docs', 'nav.generated.ts'), out);
console.log(`[gen-docs-index] ${files.length} components, ${guideFiles.length} guides`);
